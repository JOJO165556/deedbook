-- Schéma initial deedbook - tables d'audit en ajout seul
-- Non partitionnées : RANGE(received_at) imposerait received_at dans la PK,
-- incompatible avec la déduplication par event_id (cf. docs/adr D007)

CREATE SCHEMA IF NOT EXISTS deedbook;

CREATE TABLE IF NOT EXISTS deedbook.schema_migrations (
    version    text PRIMARY KEY,
    applied_at timestamptz NOT NULL DEFAULT now()
);

-- Projets/applications enregistrés (deedbook project add)
CREATE TABLE IF NOT EXISTS deedbook.apps (
    name        text PRIMARY KEY,
    token_hash  text NOT NULL,
    active      boolean NOT NULL DEFAULT true,
    created_at  timestamptz NOT NULL DEFAULT now(),
    note        text
);

-- Lots d'événements reçus
CREATE TABLE IF NOT EXISTS deedbook.audit_batches (
    batch_id       uuid PRIMARY KEY,
    app            text NOT NULL,
    schema_version text NOT NULL,
    sent_at        timestamptz,
    received_at    timestamptz NOT NULL DEFAULT now(),
    event_count    integer NOT NULL,
    signature      bytea
);

-- Événements d'audit (format : docs/specification-evenement-audit.md v1.0)
CREATE TABLE IF NOT EXISTS deedbook.audit_events (
    event_id        uuid PRIMARY KEY,
    schema_version  text NOT NULL,
    idempotency_key text NOT NULL,
    occurred_at     timestamptz NOT NULL,
    received_at     timestamptz NOT NULL DEFAULT now(),
    batch_id        uuid NOT NULL REFERENCES deedbook.audit_batches (batch_id),

    app             text NOT NULL,
    untrusted_app   boolean NOT NULL DEFAULT false,

    actor_end_user  text,
    actor_type      text NOT NULL,
    actor_role      text,
    service_account text,

    component       text,
    ip              text,
    session_id      text,
    request_id      text,

    correlation_id  text,

    action          text NOT NULL,
    resource_type   text,
    resource_name   text,
    resource_id     text,

    result_status   text NOT NULL,
    result_code     text,
    result_message  text,

    change_before   jsonb,
    change_after    jsonb,

    ingest_seq      bigint GENERATED BY DEFAULT AS IDENTITY,
    integrity_seq   bigint,
    event_hash      text,
    prev_hash       text
);

-- Contraintes d'énumérations (spec §2.5, §2.6)
ALTER TABLE deedbook.audit_events
    DROP CONSTRAINT IF EXISTS audit_events_action_check,
    ADD CONSTRAINT audit_events_action_check CHECK (action IN (
        'read', 'create', 'update', 'delete', 'export',
        'login', 'logout', 'authz_change', 'config_change')),
    DROP CONSTRAINT IF EXISTS audit_events_actor_type_check,
    ADD CONSTRAINT audit_events_actor_type_check CHECK (actor_type IN (
        'human', 'service', 'agent', 'system')),
    DROP CONSTRAINT IF EXISTS audit_events_result_check,
    ADD CONSTRAINT audit_events_result_check CHECK (result_status IN (
        'success', 'denied', 'error')),
    DROP CONSTRAINT IF EXISTS audit_events_resource_type_check,
    ADD CONSTRAINT audit_events_resource_type_check CHECK (resource_type IN (
        'table', 'record', 'view', 'function', 'other') OR resource_type IS NULL);

-- Unicité : déduplication par event_id (PK) et par couple app/clé
CREATE UNIQUE INDEX IF NOT EXISTS audit_events_idempotency
    ON deedbook.audit_events (app, idempotency_key);

-- Index de recherche (spec M4)
CREATE INDEX IF NOT EXISTS audit_events_occurred_at
    ON deedbook.audit_events (occurred_at);
CREATE INDEX IF NOT EXISTS audit_events_actor
    ON deedbook.audit_events (actor_end_user, occurred_at);
CREATE INDEX IF NOT EXISTS audit_events_resource
    ON deedbook.audit_events (resource_name, occurred_at);
CREATE INDEX IF NOT EXISTS audit_events_action
    ON deedbook.audit_events (action, occurred_at);
CREATE INDEX IF NOT EXISTS audit_events_correlation
    ON deedbook.audit_events (correlation_id)
    WHERE correlation_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS audit_events_app
    ON deedbook.audit_events (app, occurred_at);

-- Immuabilité : aucune modification, suppression ou troncature
CREATE OR REPLACE FUNCTION deedbook.reject_mutation() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'deedbook: écriture interdite sur %', TG_TABLE_NAME
        USING ERRCODE = 'restrict_violation';
END $$;

DROP TRIGGER IF EXISTS audit_events_immutable ON deedbook.audit_events;
CREATE TRIGGER audit_events_immutable
    BEFORE UPDATE OR DELETE ON deedbook.audit_events
    FOR EACH ROW EXECUTE FUNCTION deedbook.reject_mutation();

DROP TRIGGER IF EXISTS audit_events_no_truncate ON deedbook.audit_events;
CREATE TRIGGER audit_events_no_truncate
    BEFORE TRUNCATE ON deedbook.audit_events
    FOR EACH STATEMENT EXECUTE FUNCTION deedbook.reject_mutation();

DROP TRIGGER IF EXISTS audit_batches_immutable ON deedbook.audit_batches;
CREATE TRIGGER audit_batches_immutable
    BEFORE UPDATE OR DELETE ON deedbook.audit_batches
    FOR EACH ROW EXECUTE FUNCTION deedbook.reject_mutation();

DROP TRIGGER IF EXISTS audit_batches_no_truncate ON deedbook.audit_batches;
CREATE TRIGGER audit_batches_no_truncate
    BEFORE TRUNCATE ON deedbook.audit_batches
    FOR EACH STATEMENT EXECUTE FUNCTION deedbook.reject_mutation();
